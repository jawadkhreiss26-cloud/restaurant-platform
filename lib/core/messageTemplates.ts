export function firstOutreachTemplate(companyName: string, restaurantName: string): string {
  return `هلا بيك أستاذ، وياك المساعد الرقمي من ${companyName}. شفنا مطعم ${restaurantName} وحبّينا نجهز إلكم نموذج أولي يوضح شلون ممكن يصير عندكم موقع ومنيو إلكتروني مرتب. إذا تسمح، أرسل لك الرابط تشوفه؟`;
}

export function sharePreviewTemplate(previewUrl: string): string {
  return `هذا النموذج الأولي إلكم:\n${previewUrl}\nرتّبنا بيه معلومات المطعم والمنيو والموقع، ويشتغل مضبوط عالموبايل. الزبون يگدر يشوف الأصناف، يوصل للموقع ويتواصل وياكم مباشرة من خلال الإنستغرام أو المسنجر.\nشوفه براحتك، وكل المعلومات قابلة للتعديل قبل التفعيل.`;
}

export function closingTemplate(priceUsd: number): string {
  return `تمام أستاذ، نضبط الملاحظات ونفعّل الموقع إلكم. سعر الباقة ${priceUsd} دولار، وتشمل إنشاء الموقع والمنيو وربط حسابات التواصل، وياها استضافة لمدة ثلاثة أشهر. بعد الثلاثة أشهر تگدر تجددها شهرياً أو سنوياً. أرسل لك رابط الدفع حتى نبدأ بالتفعيل؟`;
}

